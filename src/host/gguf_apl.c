/* gguf_apl.c: write a GGUF model's tensor index and the hyperparameters of
 * the qwen35 architecture as a GNU APL script, so the APL program can seek to
 * any tensor and read and dequantize it itself. C does the indexing; APL does
 * the arithmetic. Only the header is read.
 *
 *   gguf_apl FILE > index.apl
 *
 * Defines GGUF_PATH; TN TT TO TD (per tensor: name, ggml type, absolute file
 * offset, dims with ne0 first); N_BLOCK N_NEXTN N_LAYER N_EMBD N_FF N_HEAD
 * N_HEAD_KV N_HEAD_DIM SSM_STATE SSM_GROUP SSM_RANK SSM_CONV FULL_EVERY
 * ROPE_DIMS FREQ_BASE RMS_EPS. */
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

#include "gguf_reader.h"

/* A number as APL text: e -> E, - -> high minus, + dropped. */
static void apl_number(const char *text)
{
    for (const char *p = text; *p; p++) {
        if (*p == '-')
            fputs("¯", stdout);
        else if (*p == 'e')
            putchar('E');
        else if (*p != '+')
            putchar(*p);
    }
}

static uint64_t need_u64(const struct gguf *g, const char *arch_key)
{
    char name[96];
    snprintf(name, sizeof name, "qwen35.%s", arch_key);
    const struct gguf_key *k = gguf_key(g, name);
    if (!k) {
        fprintf(stderr, "gguf_apl: missing key %s\n", name);
        exit(1);
    }
    return strtoull(k->text, NULL, 10);
}

int main(int argc, char **argv)
{
    struct gguf g;
    char err[512];

    if (argc != 2) {
        fprintf(stderr, "usage: gguf_apl FILE > index.apl\n");
        return 2;
    }
    if (gguf_load(&g, argv[1], err, sizeof err) != 0) {
        fprintf(stderr, "gguf_apl: %s\n", err);
        return 1;
    }
    if (g.file_size < g.need) {
        fprintf(stderr, "gguf_apl: %s is truncated\n", argv[1]);
        return 1;
    }

    printf("⍝ generated by gguf_apl: the tensor index and hyperparameters of\n⍝ %s\n", argv[1]);
    printf("⎕IO←0\nGGUF_PATH←'%s'\n", argv[1]);
    printf("TN←%" PRIu64 "⍴⊂''\nTT←%" PRIu64 "⍴0\nTO←%" PRIu64 "⍴0\nTD←%" PRIu64 "⍴⊂,0\n", g.n_tensors, g.n_tensors, g.n_tensors,
           g.n_tensors);
    for (uint64_t i = 0; i < g.n_tensors; i++) {
        const struct gguf_tensor *t = &g.tensors[i];
        printf("TN[%" PRIu64 "]←⊂'%s'\nTT[%" PRIu64 "]←%" PRIu32 "\nTO[%" PRIu64 "]←%" PRIu64 "\nTD[%" PRIu64 "]←⊂,", i, t->name, i, t->type,
               i, t->offset, i);
        for (uint32_t d = 0; d < t->n_dims; d++)
            printf("%s%" PRIu64, d ? " " : "", t->dim[d]);
        printf("\n");
    }

    uint64_t blocks = need_u64(&g, "block_count"), nextn = need_u64(&g, "nextn_predict_layers");
    printf("N_BLOCK←%" PRIu64 "\nN_NEXTN←%" PRIu64 "\nN_LAYER←%" PRIu64 "\n", blocks, nextn, blocks - nextn);
    printf("N_EMBD←%" PRIu64 "\nN_FF←%" PRIu64 "\n", need_u64(&g, "embedding_length"), need_u64(&g, "feed_forward_length"));
    printf("N_HEAD←%" PRIu64 "\nN_HEAD_KV←%" PRIu64 "\nN_HEAD_DIM←%" PRIu64 "\n", need_u64(&g, "attention.head_count"),
           need_u64(&g, "attention.head_count_kv"), need_u64(&g, "attention.key_length"));
    printf("SSM_STATE←%" PRIu64 "\nSSM_GROUP←%" PRIu64 "\nSSM_RANK←%" PRIu64 "\nSSM_CONV←%" PRIu64 "\n", need_u64(&g, "ssm.state_size"),
           need_u64(&g, "ssm.group_count"), need_u64(&g, "ssm.time_step_rank"), need_u64(&g, "ssm.conv_kernel"));
    printf("FULL_EVERY←%" PRIu64 "\nROPE_DIMS←%" PRIu64 "\n", need_u64(&g, "full_attention_interval"), need_u64(&g, "rope.dimension_count"));

    const struct gguf_key *base = gguf_key(&g, "qwen35.rope.freq_base"), *eps = gguf_key(&g, "qwen35.attention.layer_norm_rms_epsilon");
    if (!base || !eps) {
        fprintf(stderr, "gguf_apl: missing rope.freq_base or layer_norm_rms_epsilon\n");
        return 1;
    }
    fputs("FREQ_BASE←", stdout);
    apl_number(base->text);
    fputs("\nRMS_EPS←", stdout);
    apl_number(eps->text);
    putchar('\n');
    gguf_free(&g);
    return 0;
}
